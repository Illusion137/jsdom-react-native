"use strict";
const fs = require("node:fs");
const path = require("node:path");

// Inlines the default user-agent stylesheet into a JS module so it can be bundled by tools that
// have no runtime filesystem access (e.g. Metro / React Native). This keeps `getComputedStyle`
// working without `fs.readFileSync`.

const src = path.resolve(__dirname, "../lib/jsdom/browser/default-stylesheet.css");
const dest = path.resolve(__dirname, "../lib/generated/default-stylesheet.js");

const css = fs.readFileSync(src, { encoding: "utf-8" });

const output = `// This file is generated by scripts/generate-default-stylesheet.js. Do not edit.

"use strict";

module.exports = ${JSON.stringify(css)};
`;

fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, output);
